import { z } from 'zod'

/**
 * Воркспейс — проект с базой beads. В отличие от beads-ui, активный воркспейс
 * здесь не глобальное состояние сервера, а параметр запроса: две вкладки
 * с разными проектами не должны переключать друг друга.
 */

export const workspaceSchema = z.object({
  /** Устойчивый идентификатор для адреса: имя папки плюс хвост хеша пути. */
  slug: z.string(),
  /** Имя проекта — последний сегмент пути, показывается человеку. */
  name: z.string(),
  /** Абсолютный путь к корню проекта, из которого запускается `bd`. */
  path: z.string()
})

export type Workspace = z.infer<typeof workspaceSchema>
