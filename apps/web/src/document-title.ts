import { useEffect } from 'react'

/**
 * Имя вкладки. Здесь это не украшение: проект, вид и отбор живут в адресе,
 * поэтому две открытые вкладки — это два разных экрана, и если обе
 * называются «beadle», их не различить ни в переключателе окон, ни в
 * списке вкладок, ни в закладках.
 *
 * Возврата к прежнему имени нет намеренно: каждый экран называет себя сам,
 * и сбрасывать имя при уходе — значит мигать пустым названием на переходе.
 */
export function useDocumentTitle(title: string): void {
  useEffect(() => {
    document.title = title
  }, [title])
}
